// Records the promo video (title card, captions, the whole screen): node playground/record-promo.mjs [out.mp4]
import { join } from 'node:path'
import { startRecording } from './recorder.mjs'

const OUT = process.argv[2] ?? join(process.env.HOME ?? '.', 'Videos', 'lokthar-dynamic-island.mp4')
const r = await startRecording({ out: OUT, url: (slow) => `http://localhost:5199/promo.html?slow=${slow}` })
const { wait, glide, click, mouseTo, rectOf, toButton, evaluate } = r
const say = (text, sub = '') => evaluate(`window.promo.caption(${JSON.stringify(text)}, ${JSON.stringify(sub)})`)
const zoom = (z) => evaluate(`window.promo.zoom(${z})`)
const sim = (call) => evaluate(`window.promo.sim.${call}`)
const hud = (patch) => evaluate(`window.promo.patchUnified(${JSON.stringify(patch)})`)
let mouse = r.mouse()

// ---- the story -------------------------------------------------------------------------------------
await mouseTo(mouse.x, mouse.y)
await wait(3)
await evaluate('window.promo.card(null)')
await wait(0.8)

await say('A tiny bar on top of your game', 'The next events and your ping. Nothing else, until you need it.')
await wait(2.6)
await zoom(1.7)
await wait(2.4)

await evaluate('window.promo.cursor(true)')
await say('Hover to unfold it')
const bar = await rectOf('.cursor-move')
await glide(bar.x - 40, bar.y, 1.1)
await wait(1.4)

await say('Hover a button to peek at that widget', 'Right inside the bar, no window to open')
await toButton('DPS meter', 0.8)
await wait(1.7)
await toButton('Map', 0.45)
await wait(1.4)
await toButton('Kill feed', 0.45)
await wait(1.6)
await toButton('Pets and soul drops', 0.45)
await wait(1.6)

await say('Click to toggle the full widget', 'The icon lights up while its overlay is on')
await zoom(1)
await wait(1.2)
const bar2 = await rectOf('.cursor-move')
await glide(bar2.x - 40, bar2.y, 0.7)
await wait(0.9)
await toButton('DPS meter', 0.7)
await wait(0.5)
await click()
await wait(1.8)
await toButton('Kill feed', 0.5)
await wait(0.4)
await click()
await wait(2.2)
await say('One bar. Every widget, one click away.')
await toButton('DPS meter', 0.6)
await click()
await wait(0.5)
await toButton('Kill feed', 0.4)
await click()
await wait(1.2)
await zoom(1.7)
await wait(1)

// Away from it: it folds back to the compact bar.
await glide(1250, 520, 0.8)
await wait(1.2)
await evaluate('window.promo.cursor(false)')

await say('It shows what matters, when it matters')
await wait(1.2)
await say('Select a player', 'Class, combat power and gear score, as soon as you target them')
await sim('selectPlayer()')
await wait(3)
await say('Hit something', 'Your DPS and its health, on a thin line')
await sim('hitMonster(8000)')
await wait(3.4)
await say('Enemies who can attack you', 'Count on the bar; hover it for the list')
await sim('enemies()')
await wait(2.4)
await say('A field boss is alive')
await sim('fieldBoss()')
await wait(2)
await say('A Hidden Cube nearby, and where you last died')
await sim('cube()')
await wait(1.1)
await sim('died()')
await wait(2.2)
await say('Abyss Points this season', 'Counts while you farm, ends 15 minutes after the last one')
await sim('abyssKill(300)')
await wait(0.8)
await sim('abyssKill(280)')
await wait(0.8)
await sim('abyssKill(320)')
await wait(2.2)

await say('Make it blend into your game', 'Opacity all the way down to fully transparent, and flush to the top edge')
for (const o of [0.94, 0.7, 0.45, 0.2, 0]) {
  await hud({ opacity: o })
  await wait(0.7)
}
await wait(1.2)
await hud({ opacity: 0.94 })
await wait(0.6)

await sim('reset()')
await say('')
await evaluate("window.promo.card('outro')")
await wait(4.2)

await r.finish()
