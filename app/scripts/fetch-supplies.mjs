/**
 * Every supply request of the game, from questlog.gg's database, for the sessions (what you handed
 * in and what it gave): its name, how many it wants, and its rewards, set by the game.
 *
 * Writes src/shared/supplies.ts: supply request id -> [name, required count, rewards], each reward
 * [item id, amount].
 *
 *   node scripts/fetch-supplies.mjs
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const APP = join(dirname(fileURLToPath(import.meta.url)), '..')
const DATA = join(APP, 'src', 'shared', 'supplies.ts')
const API = 'https://questlog.gg/aion-2/api/trpc'
const HEADERS = { 'user-agent': 'aion2-drop-tracker (personal pet collection tracker)', accept: 'application/json' }
const PAUSE_MS = 150
/** The most pages questlog serves a list. */
const MAX_PAGES = 25

const sleep = (ms) => new Promise((r) => setTimeout(r, ms))

async function call(proc, input) {
  for (let attempt = 1; ; attempt++) {
    const res = await fetch(`${API}/${proc}?input=${encodeURIComponent(JSON.stringify({ language: 'en', ...input }))}`, { headers: HEADERS })
    await sleep(PAUSE_MS)
    if (res.ok) return (await res.json()).result.data
    if (attempt >= 3) throw new Error(`${proc} ${JSON.stringify(input)}: HTTP ${res.status}`)
    await sleep(2000 * attempt)
  }
}

/** Every id of a list: whole, else a tab at a time (tab_01, tab_02...). */
async function ids() {
  const found = new Set()
  const add = async (filter) => {
    const p1 = await call('database.getSupplyRequests', { page: 1, ...filter })
    const pages = [p1]
    for (let n = 2; n <= Math.min(p1.pageCount, MAX_PAGES); n++) pages.push(await call('database.getSupplyRequests', { page: n, ...filter }))
    for (const p of pages) for (const r of p.pageData) if (!r.isDisabled) found.add(r.id)
    return { pages: p1.pageCount, tabs: new Set(pages.flatMap((p) => p.pageData.map((r) => r.mainCategory))) }
  }
  const { pages, tabs } = await add({})
  if (pages > MAX_PAGES) {
    for (let n = 1; n <= 12; n++) tabs.add(`tab_${String(n).padStart(2, '0')}`)
    for (const mainCategory of tabs) {
      const sub = await add({ mainCategory })
      if (sub.pages > MAX_PAGES) console.warn(`${mainCategory}: more than ${MAX_PAGES} pages, some not listed`)
    }
  }
  return [...found]
}

const all = await ids()
console.log(`${all.length} supply requests`)
const out = {}
let n = 0
for (const id of all) {
  const r = await call('database.getSupplyRequest', { id })
  if (r) out[id] = [r.name, r.requiredCount ?? 1, (r.supplyRequestRewardsItems ?? []).map((i) => [Number(i.id), i.count ?? 1])]
  if (++n % 100 === 0) console.log(`${n}/${all.length}`)
}
const sorted = Object.fromEntries(Object.entries(out).sort(([a], [b]) => Number(a) - Number(b)))
const header = '// Every supply request: [name, required count, rewards: [item id, amount]]. Generated by scripts/fetch-supplies.mjs (questlog.gg); do not edit.\n'
writeFileSync(DATA, `${header}export const SUPPLIES: Record<string, [name: string, required: number, rewards: [item: number, amount: number][]]> = ${JSON.stringify(sorted)}\n`)
console.log(`${Object.keys(sorted).length} supply requests -> ${DATA}`)
