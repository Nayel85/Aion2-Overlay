/**
 * Snapshot each dungeon's bosses (those its end cube counts: questlog's `dungeonHasBossNpcs`, the final
 * one last), for the Personal bests' grids:
 *
 *   node scripts/fetch-dungeon-bosses.mjs
 *
 * Writes src/shared/dungeonBosses.ts: world id -> boss names. The dungeons come from src/shared/zones.ts
 * (dungeon types `party`, `raid`, `awaken`). Source: questlog.gg's Aion 2 database (database.getDungeon),
 * used with credit; one request each, with a pause between them. Checked against the game (2026-11-25):
 * Fire Temple's Ignus, Murute and Kromede's Desire (not Silver Blade Rotan).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const APP = join(dirname(fileURLToPath(import.meta.url)), '..')
const API = 'https://questlog.gg/aion-2/api/trpc'
const HEADERS = { 'user-agent': 'aion2-drop-tracker (personal pet collection tracker)', accept: 'application/json' }
const PAUSE_MS = 300
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))

const zones = readFileSync(join(APP, 'src', 'shared', 'zones.ts'), 'utf8')
const ids = [...zones.matchAll(/"(\d+)":\["[^"]*",[^,]*,"(party|raid|awaken)",/g)].map((m) => m[1])
const out = {}
for (const id of ids) {
  const res = await fetch(`${API}/database.getDungeon?input=${encodeURIComponent(JSON.stringify({ language: 'en', id }))}`, { headers: HEADERS })
  if (res.ok) {
    const bosses = ((await res.json()).result.data?.dungeonHasBossNpcs ?? []).map((n) => n.name).filter(Boolean)
    if (bosses.length) out[id] = bosses
  } else console.warn(`  ${id}: HTTP ${res.status}`)
  await sleep(PAUSE_MS)
}
const header = "// Each dungeon's bosses (its end cube's, the final one last), by world id. Generated by scripts/fetch-dungeon-bosses.mjs (questlog.gg); do not edit.\n"
writeFileSync(join(APP, 'src', 'shared', 'dungeonBosses.ts'), `${header}export const DUNGEON_BOSSES: Record<string, string[]> = ${JSON.stringify(out)}\n`)
console.log(`${Object.keys(out).length} dungeons with their bosses`)
