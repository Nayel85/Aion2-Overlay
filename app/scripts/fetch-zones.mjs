/**
 * Snapshot the game's zones by id: what the Session page calls the instances you earn in.
 *
 *   node scripts/fetch-zones.mjs
 *
 * Writes src/shared/zones.ts: world id (as the engine reads it: the corridors are 503001-503003)
 * -> [name, kind, type, difficulty, stage], kind being questlog's sub-category when it has one
 * (`arenacombat`, `arenactf`, `suppression`, `wave`...), type its dungeon type (`quest`, `ascension`,
 * `daily`, `matching`, `abyssartifact`...), difficulty and stage a party dungeon's mode (`easy`:
 * Exploration, `normal` / `advanced`: Conquest's Normal and Hard, `hard` with a stage 1-4:
 * Transcendence) or a raid's, each null when it has none.
 *
 * Source: questlog.gg's dungeon database (global client, `en`): every page of database.getDungeons,
 * then each zone's database.getDungeon for its type. Their data, used with credit; a one-time
 * snapshot, sequential requests with a pause between them (a few minutes).
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const APP = join(dirname(fileURLToPath(import.meta.url)), '..')
const DATA = join(APP, 'src', 'shared', 'zones.ts')
const API = 'https://questlog.gg/aion-2/api/trpc'
const LANGUAGE = 'en'
const HEADERS = { 'user-agent': 'aion2-drop-tracker (personal pet collection tracker)', accept: 'application/json' }
const PAUSE_MS = 250

const sleep = (ms) => new Promise((r) => setTimeout(r, ms))

async function trpc(proc, input) {
  const url = `${API}/${proc}?input=${encodeURIComponent(JSON.stringify(input))}`
  const res = await fetch(url, { headers: HEADERS })
  if (!res.ok) throw new Error(`${proc} ${JSON.stringify(input)}: HTTP ${res.status}`)
  return (await res.json()).result.data
}

const zones = {}
const first = await trpc('database.getDungeons', { language: LANGUAGE, page: 1 })
for (let n = 1; n <= first.pageCount; n++) {
  const data = n === 1 ? first : await trpc('database.getDungeons', { language: LANGUAGE, page: n })
  for (const z of data.pageData) zones[z.id] = [z.name, z.subCategory ?? null, null, null, null]
  await sleep(PAUSE_MS)
}
for (const id of Object.keys(zones)) {
  const z = await trpc('database.getDungeon', { language: LANGUAGE, id })
  zones[id][2] = z.dungeonType ?? null
  zones[id][3] = z.difficulty ?? null
  zones[id][4] = z.stage ?? null
  await sleep(PAUSE_MS)
}
const sorted = Object.fromEntries(Object.entries(zones).sort(([a], [b]) => Number(a) - Number(b)))
const header = "// The game's zones by id: [name, kind, dungeon type, difficulty, stage]. Generated by scripts/fetch-zones.mjs (questlog.gg); do not edit.\n"
writeFileSync(DATA, `${header}export const ZONES: Record<string, [string, string | null, string | null, string | null, number | null]> = ${JSON.stringify(sorted)}\n`)
console.log(`${Object.keys(sorted).length} zones -> ${DATA}`)
