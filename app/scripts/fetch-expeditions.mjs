/**
 * Snapshot each expedition's guaranteed chest: how many cubes opened before it (questlog's
 * `ceilingCount`), for the Expeditions page:
 *
 *   node scripts/fetch-expeditions.mjs
 *
 * Writes src/shared/expeditionCeilings.ts: world id -> cubes. The party dungeons come from
 * src/shared/zones.ts (dungeon type `party`); those with no ceiling (raids, the Abyss's) are left out.
 * Source: questlog.gg's Aion 2 database (database.getDungeon), used with credit; one request each,
 * with a pause between them. Checked against the game (2026-11-24): Draupnir Conquest 3 of 14, Fire
 * Temple Conquest 4 of 28.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const APP = join(dirname(fileURLToPath(import.meta.url)), '..')
const API = 'https://questlog.gg/aion-2/api/trpc'
const HEADERS = { 'user-agent': 'aion2-drop-tracker (personal pet collection tracker)', accept: 'application/json' }
const PAUSE_MS = 300
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))

const zones = readFileSync(join(APP, 'src', 'shared', 'zones.ts'), 'utf8')
const ids = [...zones.matchAll(/"(\d+)":\["[^"]*",[^,]*,"party",/g)].map((m) => m[1])
const out = {}
for (const id of ids) {
  const res = await fetch(`${API}/database.getDungeon?input=${encodeURIComponent(JSON.stringify({ language: 'en', id }))}`, { headers: HEADERS })
  if (res.ok) {
    const ceiling = (await res.json()).result.data?.ceilingCount
    if (ceiling) out[id] = ceiling
  } else console.warn(`  ${id}: HTTP ${res.status}`)
  await sleep(PAUSE_MS)
}
const header = "// Each expedition's guaranteed chest: cubes opened before it, by world id. Generated by scripts/fetch-expeditions.mjs (questlog.gg); do not edit.\n"
writeFileSync(join(APP, 'src', 'shared', 'expeditionCeilings.ts'), `${header}export const EXPEDITION_CEILINGS: Record<string, number> = ${JSON.stringify(out)}\n`)
console.log(`${Object.keys(out).length} expeditions with a guaranteed chest`)
