/**
 * Every crafting recipe of the game, from questlog.gg's database, for the gathering outcome's
 * window (pages/GatherPage.vue): what a craft makes, and what it makes on a proc, known as it starts.
 *
 * Writes src/shared/recipes.ts: recipe id -> [product, proc product | null, proc chance 0-1, craft], each product
 * [item id, quantity, name, grade, icon]. A proc is the better item (a green Splendent one where a
 * white one is crafted) or the same one twice: the quantity says which. Icons are paths under
 * questlog's Texture/ (main/icons.ts fetches them when first shown).
 *
 *   node scripts/fetch-recipes.mjs
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const APP = join(dirname(fileURLToPath(import.meta.url)), '..')
const DATA = join(APP, 'src', 'shared', 'recipes.ts')
const API = 'https://questlog.gg/aion-2/api/trpc'
const HEADERS = { 'user-agent': 'aion2-drop-tracker (personal pet collection tracker)', accept: 'application/json' }
const PAUSE_MS = 150
/** The most pages questlog serves a list. */
const MAX_PAGES = 25

const sleep = (ms) => new Promise((r) => setTimeout(r, ms))

async function call(proc, input) {
  for (let attempt = 1; ; attempt++) {
    const res = await fetch(`${API}/${proc}?input=${encodeURIComponent(JSON.stringify({ language: 'en', ...input }))}`, { headers: HEADERS })
    await sleep(PAUSE_MS)
    if (res.ok) return (await res.json()).result.data
    if (attempt >= 3) throw new Error(`${proc} ${JSON.stringify(input)}: HTTP ${res.status}`)
    await sleep(2000 * attempt)
  }
}

/** Every recipe id: the whole list, else a crafting category at a time. */
async function ids() {
  const first = await call('database.getRecipes', { page: 1 })
  const found = new Set()
  const add = async (filter) => {
    const p1 = await call('database.getRecipes', { page: 1, ...filter })
    const pages = [p1]
    for (let n = 2; n <= Math.min(p1.pageCount, MAX_PAGES); n++) pages.push(await call('database.getRecipes', { page: n, ...filter }))
    for (const p of pages) for (const r of p.pageData) if (!r.isDisabled) found.add(r.id)
    return { pages: p1.pageCount, cats: new Set(pages.flatMap((p) => p.pageData.map((r) => r.mainCategory))) }
  }
  if (first.pageCount <= MAX_PAGES) {
    await add({})
    return [...found]
  }
  // Too many for one list: by crafting category (those of the pages served, and the usual ones).
  const { cats } = await add({})
  for (const c of ['blacksmithing', 'armorsmithing', 'handicrafting', 'alchemy', 'cooking', 'tailoring', 'menuisier', 'construction']) cats.add(c)
  for (const mainCategory of cats) {
    const { pages } = await add({ mainCategory })
    if (pages > MAX_PAGES) console.warn(`${mainCategory}: more than ${MAX_PAGES} pages, some not listed`)
  }
  return [...found]
}

const TEXTURES = '/assets/Game/UI/Resource/Texture/'
const iconOf = (path) => {
  if (!path?.startsWith(TEXTURES)) return null
  const rel = path.slice(TEXTURES.length).replace(/\.[^/]+$/, '')
  return /^[\w/-]+$/.test(rel) ? rel : null
}
const product = (i) => (i ? [Number(i.id), i.quantity ?? 1, i.name, i.grade ?? 11, iconOf(i.icon)] : null)

const all = await ids()
console.log(`${all.length} recipes`)
const recipes = {}
let n = 0
for (const id of all) {
  const r = await call('database.getRecipe', { id })
  const out = r?.recipeOutputItems
  // The proc's chance, in ten-thousandths (2500: 25%).
  if (out?.productItem) recipes[id] = [product(out.productItem), product(out.comboProductItem), out.comboProductItem ? (out.comboProbability ?? 0) / 10_000 : 0, r.mainCategory ?? 'other']
  if (++n % 100 === 0) console.log(`${n}/${all.length}`)
}
const sorted = Object.fromEntries(Object.entries(recipes).sort(([a], [b]) => Number(a) - Number(b)))
const header =
  '// Every crafting recipe: [product, proc product | null, proc chance 0-1, craft (blacksmithing...)], each [item id, quantity, name, grade, icon]. Generated by scripts/fetch-recipes.mjs (questlog.gg); do not edit.\n'
writeFileSync(
  DATA,
  `${header}export type RecipeProduct = [item: number, quantity: number, name: string, grade: number, icon: string | null]\nexport const RECIPES: Record<string, [plain: RecipeProduct, proc: RecipeProduct | null, procChance: number, craft: string]> = ${JSON.stringify(sorted)}\n`,
)
console.log(`${Object.keys(sorted).length} recipes -> ${DATA}`)
