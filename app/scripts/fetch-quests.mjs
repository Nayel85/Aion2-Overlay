/**
 * Snapshot the duty missions' names (the quests of the duty board), for the Session page:
 *
 *   node scripts/fetch-quests.mjs
 *
 * Writes src/shared/quests.ts: quest id -> [name, grade]. Source: questlog.gg's quest database
 * (global client, `en`): database.getQuests of the `dutymission` category, every page. Their data,
 * used with credit; a one-time snapshot, sequential requests with a pause between them.
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const APP = join(dirname(fileURLToPath(import.meta.url)), '..')
const DATA = join(APP, 'src', 'shared', 'quests.ts')
const API = 'https://questlog.gg/aion-2/api/trpc'
const HEADERS = { 'user-agent': 'aion2-drop-tracker (personal pet collection tracker)', accept: 'application/json' }
const PAUSE_MS = 250
/** Duty missions on the board that questlog does not list (or lists as disabled): their names from the game. */
const KNOWN = {
  1302157: ['...And Justice for All', 11], // the owner's 2026-11-24 board
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
async function page(n) {
  const input = { language: 'en', page: n, mainCategory: 'dutymission' }
  const res = await fetch(`${API}/database.getQuests?input=${encodeURIComponent(JSON.stringify(input))}`, { headers: HEADERS })
  if (!res.ok) throw new Error(`getQuests page ${n}: HTTP ${res.status}`)
  await sleep(PAUSE_MS)
  return (await res.json()).result.data
}

const quests = {}
const first = await page(1)
for (let n = 1; n <= first.pageCount; n++) for (const q of (n === 1 ? first : await page(n)).pageData) if (!q.isDisabled) quests[q.id] = [q.name, q.grade ?? 11]
for (const [id, q] of Object.entries(KNOWN)) quests[id] ??= q
const sorted = Object.fromEntries(Object.entries(quests).sort(([a], [b]) => Number(a) - Number(b)))
const header = "// The duty missions by quest id: [name, grade]. Generated by scripts/fetch-quests.mjs (questlog.gg); do not edit.\n"
writeFileSync(DATA, `${header}export const QUESTS: Record<string, [string, number]> = ${JSON.stringify(sorted)}\n`)
console.log(`${Object.keys(sorted).length} quests -> ${DATA}`)
