/**
 * Every gathering spot's kind of the game, from questlog.gg's database, for the gathering outcome's
 * window (pages/GatherPage.vue): what each gives, by the grade the game rolls as a gathering starts.
 *
 * Writes src/shared/gatherables.ts: questlog's gatherable id -> [name, regions, groups], groups by
 * the game's group number (1 the plain item, 2 ranked up, 3, 4...): [item id, count, name, grade,
 * icon]. Icons are paths under questlog's Texture/ (main/icons.ts fetches them when first shown).
 *
 *   node scripts/fetch-gatherables.mjs
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const APP = join(dirname(fileURLToPath(import.meta.url)), '..')
const DATA = join(APP, 'src', 'shared', 'gatherables.ts')
const API = 'https://questlog.gg/aion-2/api/trpc'
const HEADERS = { 'user-agent': 'aion2-drop-tracker (personal pet collection tracker)', accept: 'application/json' }
const PAUSE_MS = 150

const sleep = (ms) => new Promise((r) => setTimeout(r, ms))

async function call(proc, input) {
  for (let attempt = 1; ; attempt++) {
    const res = await fetch(`${API}/${proc}?input=${encodeURIComponent(JSON.stringify({ language: 'en', ...input }))}`, { headers: HEADERS })
    await sleep(PAUSE_MS)
    if (res.ok) return (await res.json()).result.data
    if (attempt >= 3) throw new Error(`${proc} ${JSON.stringify(input)}: HTTP ${res.status}`)
    await sleep(2000 * attempt)
  }
}

const TEXTURES = '/assets/Game/UI/Resource/Texture/'
const iconOf = (path) => {
  if (!path?.startsWith(TEXTURES)) return null
  const rel = path.slice(TEXTURES.length).replace(/\.[^/]+$/, '')
  return /^[\w/-]+$/.test(rel) ? rel : null
}

const first = await call('database.getGatherables', { page: 1 })
const ids = first.pageData.map((g) => g.id)
for (let n = 2; n <= first.pageCount; n++) ids.push(...(await call('database.getGatherables', { page: n })).pageData.map((g) => g.id))
console.log(`${ids.length} gatherables`)

const out = {}
for (const id of ids) {
  const g = await call('database.getGatherable', { id })
  if (!g || g.isDisabled) continue
  const groups = {}
  for (const d of g.gatherableDropsItems ?? []) {
    // The bonus items (a skin bundle) come seldom with any grade: not what the grade gives.
    if (d.isBonus || groups[d.groupKey]) continue
    groups[d.groupKey] = [Number(d.id), d.count ?? 1, d.name, d.grade ?? 11, iconOf(d.icon)]
  }
  const regions = (g.gatherableIsFoundInRegions ?? []).map((r) => Number(r.id))
  out[id] = [g.name, regions, groups]
}
const sorted = Object.fromEntries(Object.entries(out).sort(([a], [b]) => Number(a) - Number(b)))
const header =
  "// Every gathering spot's kind: [name, regions, groups by grade (1 plain, 2 ranked up...): [item id, count, name, grade, icon]]. Generated by scripts/fetch-gatherables.mjs (questlog.gg); do not edit.\n"
writeFileSync(
  DATA,
  `${header}export type GatherDrop = [item: number, count: number, name: string, grade: number, icon: string | null]\nexport const GATHERABLES: Record<string, [name: string, regions: number[], groups: Record<string, GatherDrop>]> = ${JSON.stringify(sorted)}\n`,
)
console.log(`${Object.keys(sorted).length} gatherables -> ${DATA}`)
