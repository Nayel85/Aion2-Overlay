/**
 * Snapshot what each stone set in equipment gives (manastones, soulstones), for the Inventory page:
 *
 *   node scripts/fetch-stones.mjs
 *
 * Writes src/shared/stones.ts: stone item id -> { stat id: [[grade, value], ...] }, the ranks in
 * order (an item record's stone rank 1 is the first). The stones are the items src/shared/items.ts
 * lists as `magicstone` (run scripts/fetch-items.mjs first). Source: questlog.gg's item database
 * (global client, `en`): database.getItem's `usableInfo.magicStoneStats`. Their data, used with
 * credit; a one-time snapshot, sequential requests with a pause between them.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const APP = join(dirname(fileURLToPath(import.meta.url)), '..')
const DATA = join(APP, 'src', 'shared', 'stones.ts')
const API = 'https://questlog.gg/aion-2/api/trpc'
const HEADERS = { 'user-agent': 'aion2-drop-tracker (personal pet collection tracker)', accept: 'application/json' }
const PAUSE_MS = 250

const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
const src = readFileSync(join(APP, 'src', 'shared', 'items.ts'), 'utf8')
const items = JSON.parse(src.slice(src.indexOf('= ') + 2))
const ids = Object.entries(items).filter(([, i]) => i[3] === 'magicstone').map(([id]) => id)
const stones = {}
for (const id of ids) {
  const res = await fetch(`${API}/database.getItem?input=${encodeURIComponent(JSON.stringify({ language: 'en', id }))}`, { headers: HEADERS })
  if (!res.ok) throw new Error(`getItem ${id}: HTTP ${res.status}`)
  const stats = (await res.json()).result.data?.usableInfo?.magicStoneStats
  if (stats?.length) stones[id] = Object.fromEntries(stats.map((s) => [s.statId, s.stats.map((r) => [r.grade, r.value])]))
  await sleep(PAUSE_MS)
}
const header = "// What each stone set in equipment gives by item id: { stat id: [[grade, value] by rank] }. Generated by scripts/fetch-stones.mjs (questlog.gg); do not edit.\n"
writeFileSync(DATA, `${header}export const STONES: Record<string, Record<string, [number, number][]>> = ${JSON.stringify(stones)}\n`)
console.log(`${Object.keys(stones).length} of ${ids.length} stones -> ${DATA}`)
